test("song coverage matrix: 35 real-world Spotify tracks match and score reliably with 100% precision", () => {
  for (const song of SONG_COVERAGE_MATRIX) {
    const scored = scoreLrclibCandidate(song.sampleRecord, {
      title: song.spotifyTitle,
      artist: song.spotifyArtist,
      album: song.spotifyAlbum,
      durationSec: song.spotifyDurationSec,
    });

    assert.ok(
      scored,
      `Failed to match candidate for [${song.category}] "${song.spotifyTitle}" by "${song.spotifyArtist}"`,
    );

    assert.ok(
      scored.score >= 80,
      `Score too low (${scored.score}) for [${song.category}] "${song.spotifyTitle}" by "${song.spotifyArtist}"`,
    );

    if (song.expectedState === "synced") {
      assert.equal(
        scored.hasUsableSyncedLyrics,
        true,
        `Expected synced lyrics for "${song.spotifyTitle}"`,
      );
    } else if (song.expectedState === "instrumental") {
      assert.equal(
        Boolean(song.sampleRecord.instrumental),
        true,
        `Expected instrumental flag for "${song.spotifyTitle}"`,
      );
    }
  }
});
